// The availability matrix.
//
// Every gated construct, decided once per compatibility level and once per engine profile. The
// point of printing it is that a gate is data: a feature that is available everywhere, or nowhere,
// or that no scenario exercises, is visible as a row rather than as an assumption.
//
// Usage:
//   node scripts/report-availability-matrix.mjs                    # summary to stdout
//   node scripts/report-availability-matrix.mjs --markdown <path>  # full document

import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const packageRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const { featureAvailability, platformFeatures } = require(join(packageRoot, "dist", "index.js"));

/** Every level the package models, newest last. 180 is the preview level. */
const LEVELS = [80, 90, 100, 110, 120, 130, 140, 150, 160, 170, 180];

/** Every engine profile a document can be analysed under, including the unidentified one. */
const PROFILES = [
    "sql-server",
    "azure-sql-database",
    "azure-sql-managed-instance",
    "azure-synapse-dedicated",
    "fabric-warehouse",
    "unknown",
];

const SYMBOLS = { available: "yes", unavailable: "no", deferred: "defer" };

const manifest = JSON.parse(
    await readFile(
        join(packageRoot, "test", "resources", "dialect", "dialect-scenarios.json"),
        "utf8",
    ),
);
const covered = coverage(manifest);

const markdownIndex = process.argv.indexOf("--markdown");
if (markdownIndex >= 0) {
    await writeFile(process.argv[markdownIndex + 1], render(), "utf8");
}
printSummary();

/** Which features have a scenario that accepts them and one that reports them. */
function coverage(source) {
    const supported = new Set();
    const gated = new Set();
    for (const scenario of source.scenarios) {
        for (const feature of scenario.expectFeatures ?? []) {
            if (scenario.classification === "unsupportedProfile") gated.add(feature);
        }
        for (const node of scenario.expectNodes ?? []) {
            if (scenario.classification !== "valid") continue;
            for (const feature of platformFeatures) {
                if (feature.nodes.includes(node)) supported.add(feature.id);
            }
        }
    }
    return { supported, gated };
}

/** The decision for one feature under one profile, with preview features enabled. */
function decide(feature, engineProfile, level) {
    return featureAvailability(feature, {
        engineProfile,
        ...(level === undefined
            ? {}
            : { serverMajorVersion: Math.floor(level / 10), compatibilityLevel: level }),
        previewFeatures: true,
    });
}

function render() {
    let out = "# Availability matrix\n\n";
    out +=
        "Generated by `node scripts/report-availability-matrix.mjs --markdown <path>`; regenerate\n" +
        "after a registry change rather than editing by hand.\n\n";
    out +=
        "Every value is one `FeatureAvailabilityDecision`. `defer` is a decision, not a gap: while a\n" +
        "required fact is missing nothing is declared unavailable, which is why the unidentified\n" +
        "engine column is entirely deferred. Preview features are enabled for this report, so a\n" +
        "preview-only row shows its version gate rather than its preview gate.\n\n";

    out += "## By compatibility level, on SQL Server\n\n";
    out += `| feature | family | ${LEVELS.join(" | ")} |\n`;
    out += `|---|---|${LEVELS.map(() => "---").join("|")}|\n`;
    for (const feature of platformFeatures) {
        const cells = LEVELS.map((level) => SYMBOLS[decide(feature, "sql-server", level)]);
        out += `| \`${feature.id}\` | ${feature.family} | ${cells.join(" | ")} |\n`;
    }

    out += "\n## By engine profile, at the newest released level\n\n";
    out += `| feature | ${PROFILES.join(" | ")} |\n`;
    out += `|---|${PROFILES.map(() => "---").join("|")}|\n`;
    for (const feature of platformFeatures) {
        const cells = PROFILES.map((profile) =>
            profile === "unknown"
                ? SYMBOLS[decide(feature, profile, undefined)]
                : SYMBOLS[decide(feature, profile, 170)],
        );
        out += `| \`${feature.id}\` | ${cells.join(" | ")} |\n`;
    }

    out += "\n## Scenario coverage\n\n";
    out +=
        "A gate that no scenario exercises is a gate nothing proves. Each feature needs one\n" +
        "scenario at a level that accepts it and one at a level or profile that reports it.\n\n";
    out += "| feature | accepted somewhere | reported somewhere |\n|---|---|---|\n";
    for (const feature of platformFeatures) {
        out += `| \`${feature.id}\` | ${covered.supported.has(feature.id) ? "yes" : "**missing**"} | ${
            covered.gated.has(feature.id) ? "yes" : "**missing**"
        } |\n`;
    }
    return out;
}

function printSummary() {
    const missingSupported = platformFeatures.filter(
        (feature) => !covered.supported.has(feature.id),
    );
    const missingGated = platformFeatures.filter((feature) => !covered.gated.has(feature.id));
    console.log(`Registry features: ${platformFeatures.length}`);
    console.log(`Levels modelled: ${LEVELS.join(", ")}`);
    console.log(`Profiles modelled: ${PROFILES.join(", ")}`);
    console.log(`Without an accepting scenario: ${missingSupported.length}`);
    if (missingSupported.length > 0) {
        console.log(`  ${missingSupported.map((feature) => feature.id).join(", ")}`);
    }
    console.log(`Without a reporting scenario: ${missingGated.length}`);
    if (missingGated.length > 0) {
        console.log(`  ${missingGated.map((feature) => feature.id).join(", ")}`);
    }
}
