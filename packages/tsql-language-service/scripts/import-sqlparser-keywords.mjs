import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const packageDirectory = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const defaultSourceRoot = path.resolve(packageDirectory, "..", "..", "..", "SqlParser");
const sourceRoot = path.resolve(readArgument("--sqlparser-root") ?? defaultSourceRoot);
const parserDirectory = path.join(
    sourceRoot,
    "src",
    "Microsoft",
    "SqlServer",
    "Management",
    "SqlParser",
    "Parser",
);
const reservedPath = path.join(parserDirectory, "Keywords", "keywords.txt");
const contextualPath = path.join(parserDirectory, "ContextKeywords.txt");
const outputPath = path.join(packageDirectory, "src", "syntax", "keywords.generated.ts");

const reserved = parseReserved(await readFile(reservedPath, "utf8"));
const contextual = parseContextual(await readFile(contextualPath, "utf8"));
const source = render(reserved, contextual);
await writeFile(outputPath, source, "utf8");
console.log(
    `Generated ${path.relative(packageDirectory, outputPath)} with ${reserved.length} reserved and ${contextual.length} contextual keywords.`,
);

function readArgument(name) {
    const index = process.argv.indexOf(name);
    return index < 0 ? undefined : process.argv[index + 1];
}

function parseReserved(text) {
    const byName = new Map();
    for (const rawLine of text.split(/\r?\n/u)) {
        const line = rawLine.trim();
        if (!line || line.startsWith("#")) continue;
        const [name, token, minimumCompatibility] = line.split(/\s+/u);
        if (!name || !token || !minimumCompatibility) {
            throw new Error(`Unrecognized reserved-keyword row: ${rawLine}`);
        }
        byName.set(name.toLowerCase(), {
            name: name.toLowerCase(),
            token,
            minimumCompatibility: Number.parseInt(minimumCompatibility, 10),
        });
    }
    return [...byName.values()].sort((left, right) => left.name.localeCompare(right.name));
}

function parseContextual(text) {
    const byName = new Map();
    let context;
    for (const rawLine of text.split(/\r?\n/u)) {
        const line = rawLine.trim();
        if (!line || line.startsWith("#")) continue;
        if (line.startsWith("!!")) {
            context = line
                .slice(2)
                .replace(/^OPT_/iu, "")
                .replace(/_SUBTOKENS$/iu, "")
                .toLowerCase();
            continue;
        }
        const [name, token] = line.split(/\s+/u);
        if (!context || !name || !token) {
            throw new Error(`Unrecognized contextual-keyword row: ${rawLine}`);
        }
        const key = name.toLowerCase();
        const entry = byName.get(key) ?? { name: key, contexts: [] };
        entry.contexts.push({ context, token });
        byName.set(key, entry);
    }
    return [...byName.values()]
        .map((entry) => ({
            ...entry,
            contexts: entry.contexts.sort(
                (left, right) =>
                    left.context.localeCompare(right.context) ||
                    left.token.localeCompare(right.token),
            ),
        }))
        .sort((left, right) => left.name.localeCompare(right.name));
}

function render(reserved, contextual) {
    const reservedRows = reserved
        .map(
            ({ name, token, minimumCompatibility }) =>
                `    ${JSON.stringify(name)}: { token: ${JSON.stringify(token)}, minimumCompatibility: ${minimumCompatibility} },`,
        )
        .join("\n");
    const contextualRows = contextual
        .map(({ name, contexts }) => `    ${JSON.stringify(name)}: ${JSON.stringify(contexts)},`)
        .join("\n");
    return `/*---------------------------------------------------------------------------------------------
 *  Copyright (c) Microsoft Corporation. All rights reserved.
 *  Licensed under the MIT License. See License.txt in the project root for license information.
 *--------------------------------------------------------------------------------------------*/

// Generated by scripts/import-sqlparser-keywords.mjs from Microsoft SqlParser's
// Keywords/keywords.txt and ContextKeywords.txt. Do not edit this file by hand.

export interface ReservedKeywordMetadata {
    readonly token: string;
    readonly minimumCompatibility: number;
}

export interface ContextualKeywordUse {
    readonly context: string;
    readonly token: string;
}

export const reservedKeywordMetadata = Object.freeze({
${reservedRows}
} satisfies Readonly<Record<string, ReservedKeywordMetadata>>);

export const contextualKeywordMetadata = Object.freeze({
${contextualRows}
} satisfies Readonly<Record<string, readonly ContextualKeywordUse[]>>);

export const reservedKeywordNames = Object.freeze(Object.keys(reservedKeywordMetadata));
export const contextualKeywordNames = Object.freeze(Object.keys(contextualKeywordMetadata));

const reservedKeywordSet = new Set<string>(reservedKeywordNames);
const contextualKeywordSet = new Set<string>(contextualKeywordNames);

export function keywordMetadata(text: string):
    | { readonly category: "reserved"; readonly minimumCompatibility: number }
    | { readonly category: "contextual"; readonly contexts: readonly ContextualKeywordUse[] }
    | undefined {
    const normalized = text.toLowerCase();
    const reserved = reservedKeywordMetadata[normalized as keyof typeof reservedKeywordMetadata];
    if (reserved) {
        return { category: "reserved", minimumCompatibility: reserved.minimumCompatibility };
    }
    const contextual =
        contextualKeywordMetadata[normalized as keyof typeof contextualKeywordMetadata];
    return contextual ? { category: "contextual", contexts: contextual } : undefined;
}

export function isReservedKeyword(text: string): boolean {
    return reservedKeywordSet.has(text.toLowerCase());
}

export function isContextualKeyword(text: string): boolean {
    return contextualKeywordSet.has(text.toLowerCase());
}

export function isTsqlKeyword(text: string): boolean {
    const normalized = text.toLowerCase();
    return reservedKeywordSet.has(normalized) || contextualKeywordSet.has(normalized);
}
`;
}
