SELECT c1,
       c2
FROM t1
ORDER BY ALL;
GO

SELECT c1,
       c2
FROM t1
ORDER BY ALL ASC;
GO

SELECT c1,
       c2
FROM t1
ORDER BY ALL DESC;
GO

SELECT *
FROM t1
ORDER BY ALL;
GO

SELECT c1,
       c2
FROM t1
ORDER BY ALL
OFFSET 2 ROWS FETCH NEXT 5 ROWS ONLY;
GO

SELECT c1
FROM t1
UNION ALL
SELECT c1
FROM t2
ORDER BY ALL;
GO

SELECT *
FROM (SELECT TOP 5 c1,
                   c2
      FROM t1
      ORDER BY ALL) AS sub;
GO

SELECT c1,
       COUNT(*) AS Cnt
FROM t1
GROUP BY c1
ORDER BY ALL;
GO

SELECT c1,
       COUNT(*) AS Cnt
FROM t1
GROUP BY c1
HAVING COUNT(*) > 1
ORDER BY ALL DESC;
GO

SELECT a.c1,
       b.c2
FROM t1 AS a
     INNER JOIN
     t2 AS b
     ON a.c1 = b.c1
WHERE b.c2 > 0
ORDER BY ALL;
GO

SELECT c1,
       COUNT(*) AS Cnt,
       SUM(COUNT(*)) OVER (ORDER BY c1 ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS RunningCnt
FROM t1
GROUP BY c1
ORDER BY ALL;
GO

CREATE VIEW v_OrderByAllView
AS
SELECT c1,
       c2
FROM t1
ORDER BY ALL
OFFSET 0 ROWS;
GO

CREATE PROCEDURE usp_OrderByAll
AS
BEGIN
    SELECT c1,
           c2
    FROM t1
    ORDER BY ALL;
END